import { StatusCodes } from "./status-codes.constant";

const STATUS_TO_ERROR_CODE: Record<number, string> = {
  [StatusCodes.CLIENT_ERROR.BAD_REQUEST]: "BAD_REQUEST",
  [StatusCodes.CLIENT_ERROR.UNAUTHORIZED]: "UNAUTHORIZED",
  [StatusCodes.CLIENT_ERROR.FORBIDDEN]: "FORBIDDEN",
  [StatusCodes.CLIENT_ERROR.NOT_FOUND]: "NOT_FOUND",
  [StatusCodes.CLIENT_ERROR.METHOD_NOT_ALLOWED]: "METHOD_NOT_ALLOWED",
  [StatusCodes.CLIENT_ERROR.CONFLICT]: "CONFLICT",
  [StatusCodes.CLIENT_ERROR.GONE]: "GONE",
  [StatusCodes.CLIENT_ERROR.PAYLOAD_TOO_LARGE]: "PAYLOAD_TOO_LARGE",
  [StatusCodes.CLIENT_ERROR.UNSUPPORTED_MEDIA_TYPE]: "UNSUPPORTED_MEDIA_TYPE",
  [StatusCodes.CLIENT_ERROR.UNPROCESSABLE_ENTITY]: "UNPROCESSABLE_ENTITY",
  [StatusCodes.CLIENT_ERROR.TOO_MANY_REQUESTS]: "TOO_MANY_REQUESTS",
  [StatusCodes.SERVER_ERROR.INTERNAL_SERVER_ERROR]: "INTERNAL_SERVER_ERROR",
  [StatusCodes.SERVER_ERROR.NOT_IMPLEMENTED]: "NOT_IMPLEMENTED",
  [StatusCodes.SERVER_ERROR.BAD_GATEWAY]: "BAD_GATEWAY",
  [StatusCodes.SERVER_ERROR.SERVICE_UNAVAILABLE]: "SERVICE_UNAVAILABLE",
  [StatusCodes.SERVER_ERROR.GATEWAY_TIMEOUT]: "GATEWAY_TIMEOUT",
};

export function errorCodeForStatus(statusCode: number): string {
  return STATUS_TO_ERROR_CODE[statusCode] ?? `HTTP_${statusCode}`;
}
